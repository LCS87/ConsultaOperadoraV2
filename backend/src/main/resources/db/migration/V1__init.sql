-- Compatível com H2 (modo PostgreSQL, dev/teste) e PostgreSQL 13+ (produção).
-- O schema é criado APENAS por Flyway: spring.jpa.hibernate.ddl-auto=validate.
-- ============================================================

-- 1) Arquivo recebido via upload (metadados + o que o motor detectou)
CREATE TABLE arquivo_origem (
    id                   BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_arquivo         VARCHAR(255) NOT NULL,
    uf                   VARCHAR(2),
    encoding             VARCHAR(32)  NOT NULL,
    delimitador_detectado VARCHAR(8),
    tamanho_bytes        BIGINT,
    hash_sha256          VARCHAR(64),
    criado_em            TIMESTAMP    NOT NULL
);

-- 2) Job de processamento (ciclo de vida + métricas acumuladas)
CREATE TABLE processamento_job (
    id                        BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    arquivo_id                BIGINT      NOT NULL REFERENCES arquivo_origem (id),
    status                    VARCHAR(20) NOT NULL,   -- NOVO | EM_EXECUCAO | CONCLUIDO | FALHA
    linhas_lidas              BIGINT      NOT NULL DEFAULT 0,
    registros_inseridos       INT         NOT NULL DEFAULT 0,
    duplicados_descartados    INT         NOT NULL DEFAULT 0,
    cnpj_invalidos_descartados INT        NOT NULL DEFAULT 0,
    por_operadora             VARCHAR(1000),
    iniciado_em               TIMESTAMP,
    finalizado_em             TIMESTAMP,
    mensagem_erro             VARCHAR(500)
);

-- 3) Registros classificados (saída do pipeline, agora consultável)
--    UNIQUE em cnpj = deduplicação PERSISTENTE entre execuções
--    (critério de aceite da Fase 4: reprocessar não duplica).
CREATE TABLE empresa_registro (
    id                   BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cnpj_digitos         VARCHAR(14) NOT NULL,          -- 14 digitos sem mascara (dedupe)
    columns              TEXT,                          -- 6 colunas cruas do export legado
    operadora            VARCHAR(20),                   -- CLARO|VIVO|TIM|OI|FIXO|SEM_OPERADORA
    uf                   VARCHAR(2),
    telefone_normalizado VARCHAR(32),
    job_id               BIGINT,
    CONSTRAINT uk_empresa_cnpj UNIQUE (cnpj_digitos)
);

CREATE INDEX idx_empresa_operadora_uf ON empresa_registro (operadora, uf);
CREATE INDEX idx_empresa_job          ON empresa_registro (job_id);

-- 4) Auditoria de descartes por duplicidade (substitui o HashSet volátil do CLI)
CREATE TABLE duplicidade_log (
    id             BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id         BIGINT      NOT NULL,
    cnpj           VARCHAR(14) NOT NULL,
    arquivo_origem VARCHAR(255),
    motivo         VARCHAR(40) NOT NULL,  -- CNPJ_JA_PERSISTIDO | DUPLICADO_INTERNO
    ocorrido_em    TIMESTAMP   NOT NULL,
    CONSTRAINT uk_dup_job_cnpj UNIQUE (job_id, cnpj)
);

CREATE INDEX idx_dup_cnpj ON duplicidade_log (cnpj);
